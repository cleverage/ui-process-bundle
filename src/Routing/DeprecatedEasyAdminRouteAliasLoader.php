namespace CleverAge\UiProcessBundle\Routing;

use CleverAge\UiProcessBundle\Controller\Admin\ProcessDashboardController;
use EasyCorp\Bundle\EasyAdminBundle\Config\Option\EA;
use Symfony\Component\Config\Loader\Loader;
use Symfony\Component\Routing\RouteCollection;

/**
 * Former names of the routes of the dashboard of the bundle, generated by EasyAdmin from its route name: "process"
 * and "process_<crud>_<action>" before 3.3, "cleverage_ui_process" and "cleverage_ui_process_<crud>_<action>" since.
 * They are deprecated aliases, removed in 4.0.
 *
 * Loads the routes generated by EasyAdmin (easyadmin.routes) only to know their names: returns the aliases only.
 *
 * @internal
 */
final class DeprecatedEasyAdminRouteAliasLoader extends Loader
{
    public const TYPE = 'cleverage_ui_process.deprecated_easyadmin_route_aliases';

    private const ROUTE_NAME = 'cleverage_ui_process';

    private const FORMER_ROUTE_NAME = 'process';

    public function load(mixed $resource, ?string $type = null): RouteCollection
    {
        /** @var RouteCollection $easyAdminRoutes */
        $easyAdminRoutes = $this->import('.', 'easyadmin.routes');
        $aliases = new RouteCollection();
        foreach ($easyAdminRoutes->all() as $name => $route) {
            if (ProcessDashboardController::class !== $route->getDefault(EA::DASHBOARD_CONTROLLER_FQCN)
                || (self::ROUTE_NAME !== $name && !str_starts_with($name, self::ROUTE_NAME.'_'))) {
                continue;
            }
            $formerName = self::FORMER_ROUTE_NAME.substr($name, \strlen(self::ROUTE_NAME));
            $aliases->addAlias($formerName, $name)->setDeprecated(
                'cleverage/ui-process-bundle',
                '3.3',
                \sprintf('The "%%alias_id%%" route alias is deprecated, use the "%s" route instead. It will be removed in 4.0.', $name),
            );
        }

        return $aliases;
    }

    public function supports(mixed $resource, ?string $type = null): bool
    {
        return self::TYPE === $type;
    }
}
